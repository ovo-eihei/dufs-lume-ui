#!/usr/bin/env python3
"""
生成演示用的「非网络素材」：PDF / ZIP / tar.gz / CSV / 日志 / 配置。

为什么自己造而不下载：这几类文件要的是**类型齐全**（README 截图要展示 PDF 预览、压缩包图标、
代码高亮、下载按钮），内容本身没人细看；自己生成就没有许可问题，体积也能压到几 KB。
这台机器没有 LibreOffice / ghostscript / ffmpeg，PDF 是手写的最小可用结构（一条 xref 表 + 一个内容流），
用 `pdftotext`/浏览器都能正常打开。

用法：
    python3 demo/make-files.py            # 生成到 demo/media/
"""

from __future__ import annotations

import gzip
import hashlib
import io
import json
import tarfile
import time
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent
MEDIA = ROOT / "media"
NOW = int(time.time() * 1000)


def pdf_bytes(lines: list[str]) -> bytes:
    """手写一个单页 PDF：Helvetica 12pt，从左上往下排。"""

    def esc(text: str) -> str:
        return text.replace("\\", r"\\").replace("(", r"\(").replace(")", r"\)")

    content_ops = ["BT", "/F1 12 Tf", "16 TL", "1 0 0 1 56 760 Tm"]
    for line in lines:
        content_ops.append(f"({esc(line)}) Tj")
        content_ops.append("T*")  # 按 TL 换行
    content_ops.append("ET")
    stream = "\n".join(content_ops).encode("latin-1")

    objects = [
        b"<< /Type /Catalog /Pages 2 0 R >>",
        b"<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
        b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 595 842] "
        b"/Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
        b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
        b"<< /Length " + str(len(stream)).encode() + b" >>\nstream\n" + stream + b"\nendstream",
    ]

    out = bytearray(b"%PDF-1.4\n%\xe2\xe3\xcf\xd3\n")
    offsets = []
    for idx, body in enumerate(objects, start=1):
        offsets.append(len(out))
        out += f"{idx} 0 obj\n".encode() + body + b"\nendobj\n"
    xref_at = len(out)
    out += f"xref\n0 {len(objects) + 1}\n".encode()
    out += b"0000000000 65535 f \n"
    for off in offsets:
        out += f"{off:010d} 00000 n \n".encode()
    out += (
        f"trailer\n<< /Size {len(objects) + 1} /Root 1 0 R >>\nstartxref\n{xref_at}\n%%EOF\n".encode()
    )
    return bytes(out)


def write(rel: str, blob: bytes) -> int:
    dest = MEDIA / rel
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(blob)
    return len(blob)


def main() -> int:
    made: list[tuple[str, int]] = []

    guide = pdf_bytes([
        "Dufs Lume UI - Deployment Guide",
        "",
        "1. Build the skin",
        "   pnpm install && pnpm build",
        "",
        "2. Serve it with dufs via --assets",
        "   dufs /var/lib/dufs --assets ./dist --allow-upload",
        "",
        "3. Cache behaviour (measured on dufs 0.47.0)",
        "   Every file under --assets is served with",
        "   cache-control: public, max-age=31536000, immutable",
        "   index.html alone is no-cache. That is why the bundle",
        "   file names carry a content hash, and why a release",
        "   replaces the whole assets directory.",
        "",
        "4. Extension endpoints",
        "   GET /__lume__/info   session probe + free/data bytes",
        "   GET /__lume__/thumb  server-side thumbnails (128/256/512)",
        "",
        "This page is generated by demo/make-files.py for the",
        "README screenshots; it is not real product documentation.",
    ])
    made.append(("docs/dufs-deployment-guide.pdf", write("docs/dufs-deployment-guide.pdf", guide)))

    readme_text = (
        "Dufs Lume UI\n==============\n\n"
        "A modern skin for the dufs static file server, shipped as a flat\n"
        "asset bundle and mounted with `dufs --assets ./dist`.\n\n"
        "See https://github.com/ovo-eihei/dufs-lume-ui\n"
    )
    license_text = "MIT License\n\nCopyright (c) 2026 ovo-eihei\n\nPermission is hereby granted...\n"
    notes_text = "v0.7.2\n- image viewer: first frame is already fitted and centred\n"
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("README.md", readme_text)
        zf.writestr("LICENSE", license_text)
        zf.writestr("release-notes.txt", notes_text)
        zf.writestr("share/index.html", "<!doctype html><title>demo</title>")
    made.append(("archives/lume-dist-sample.zip", write("archives/lume-dist-sample.zip", buf.getvalue())))

    tar_buf = io.BytesIO()
    with tarfile.open(fileobj=tar_buf, mode="w:gz") as tf:
        for name, body in (
            ("backup/etc-caddy-Caddyfile", "files.example.com {\n  reverse_proxy 127.0.0.1:5000\n}\n"),
            ("backup/dufs-unit.service", "[Unit]\nDescription=dufs file server\n"),
            ("backup/manifest.json", json.dumps({"files": 3, "generated": NOW}, indent=2)),
        ):
            info = tarfile.TarInfo(name)
            raw = body.encode()
            info.size = len(raw)
            info.mtime = int(time.time())
            tf.addfile(info, io.BytesIO(raw))
    made.append(("archives/site-backup.tar.gz", write("archives/site-backup.tar.gz", tar_buf.getvalue())))

    csv_rows = ["timestamp,endpoint,status,duration_ms,bytes"]
    for i in range(240):
        ts = time.strftime("%Y-%m-%dT%H:%M:%S", time.gmtime(1_763_000_000 + i * 37))
        endpoint = ["/share/", "/__lume__/info", "/thumb", "/api/delete"][i % 4]
        status = [200, 200, 200, 304, 401, 502][i % 6]
        csv_rows.append(f"{ts},{endpoint},{status},{18 + (i * 7) % 320},{(i * 4099) % 940000}")
    made.append(("data/access-sample.csv", write("data/access-sample.csv", ("\n".join(csv_rows) + "\n").encode())))

    log_lines = []
    for i in range(160):
        ts = time.strftime("%b %d %H:%M:%S", time.gmtime(1_763_100_000 + i * 23))
        level = "info" if i % 9 else "warn"
        log_lines.append(
            f"{ts} dufs[412]: {level} req method=GET path=/share/photos/aurora-{i % 7}.jpg "
            f"status={200 if i % 11 else 304} ip=198.51.100.{i % 250} dur={(9 + i * 3) % 480}ms"
        )
    made.append(("data/dufs-access.log", write("data/dufs-access.log", ("\n".join(log_lines) + "\n").encode())))

    cfg = {
        "listen": "127.0.0.1:5000",
        "path": "/var/lib/dufs",
        "assets": "/srv/dufs/assets",
        "allow": {"upload": True, "delete": True, "search": True, "archive": True},
        "auth": {"share": "anonymous"},
        "extensions": {"info": "127.0.0.1:8090", "thumbs": [128, 256, 512]},
    }
    made.append(("data/lume-config.json", write("data/lume-config.json", (json.dumps(cfg, indent=2) + "\n").encode())))

    total = sum(n for _, n in made)
    for rel, size in made:
        print(f"✓ {rel}  {size:,} B")
    print(f"\n本地生成的演示文件合计 {total:,} B")

    # 把清单里缺的条目补上（这些没有外部来源，许可就是本仓库自己的 MIT）
    manifest_path = ROOT / "manifest.json"
    manifest = json.loads(manifest_path.read_text(encoding="utf-8")) if manifest_path.exists() else {}
    for rel, size in made:
        manifest[rel] = {
            "source_title": "本地生成（demo/make-files.py）",
            "page": "",
            "original": "",
            "license": "MIT (本仓库生成)",
            "author": "dufs-lume-ui",
            "mime": {".pdf": "application/pdf", ".zip": "application/zip", ".gz": "application/gzip",
                     ".csv": "text/csv", ".log": "text/plain", ".json": "application/json"}
                    [Path(rel).suffix],
            "bytes": size,
            "sha256": hashlib.sha256((MEDIA / rel).read_bytes()).hexdigest(),
        }
    manifest_path.write_text(json.dumps(manifest, ensure_ascii=False, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    print(f"清单 → demo/manifest.json（{len(manifest)} 条）")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
